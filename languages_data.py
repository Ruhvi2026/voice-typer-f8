def get_ui_text(lang_code, key):
    """Returns localized string, falls back to English, then Bengali."""
    prefix = lang_code.split("-")[0].lower() if "-" in lang_code else lang_code.lower()
    trans = UI_TRANSLATIONS.get(prefix)
    if not trans:
        trans = UI_TRANSLATIONS.get("en")
    return trans.get(key, UI_TRANSLATIONS["en"].get(key, ""))
